package app.brix.core.diagnostics

import java.util.concurrent.ConcurrentHashMap

/**
 * Перечень периодических задач, работающих прямо сейчас.
 *
 * **Зачем.** К 12.09 в приложении набралось около десятка независимых таймеров:
 * тик статистики раз в секунду, опрос теплового статуса раз в пять, опрос чата
 * VK раз в четыре, перерисовка браузерного виджета по своему периоду, keepalive
 * SRTLA на каждый линк, анимации в интерфейсе. Каждый по отдельности оправдан, а
 * вместе они дают картину, которую нельзя восстановить иначе, чем читая проект
 * построчно. Разбирая полевой лог, на вопрос «что вообще работало в том эфире»
 * ответить было нечем.
 *
 * Это перестало быть теорией в тот же день: сессия 07.09 ушла в тепловой
 * `critical` за шесть с половиной минут, и установить по её логу, была ли
 * включена электронная стабилизация и крутился ли браузерный виджет, оказалось
 * невозможно. Выводы о нагреве пришлось строить на догадках о составе нагрузки.
 *
 * **Что это НЕ делает.** Реестр ничего не запускает, не останавливает и не
 * планирует — он только знает, кто заявился. Задача владеет своей корутиной как
 * и раньше; здесь появляется одна строка в диагностике и одно место, где видно
 * весь состав сразу.
 *
 * Регистрация не бесплатна по вниманию, поэтому сюда заявляются только
 * долгоживущие задачи — те, что крутятся весь эфир. Разовая задержка или
 * анимация на две секунды тут не нужны: они не меняют картину нагрузки.
 *
 * Потокобезопасен: заявляются из разных корутин и потоков, читается из тика
 * статистики.
 */
object PeriodicTasks {

    /** Заявка на работу. Снимается через [close] — обычно в `finally` или в
     *  `stop()` владельца, чтобы остановленная задача не висела в отчёте. */
    class Registration internal constructor(private val key: String) : AutoCloseable {
        override fun close() {
            active.remove(key)
        }
    }

    private val active = ConcurrentHashMap<String, Long>()

    /**
     * @param name короткое имя задачи, как её назовёт человек в разборе:
     *   `stats`, `thermal`, `vk-chat`. Если задач с одним именем может быть
     *   несколько (виджеты, линки), имя должно включать различитель.
     * @param periodMs период в миллисекундах — то, что стоит в `delay`.
     */
    fun register(name: String, periodMs: Long): Registration {
        active[name] = periodMs
        return Registration(name)
    }

    /**
     * Состав в одну строку, для лога: `stats:1.0s thermal:5.0s vk-chat:4.0s`.
     * Отсортировано по имени, чтобы строки разных сессий сравнивались глазами
     * без перестановок.
     *
     * @return пустая строка, если не заявлено ничего — тогда в логе не будет
     *   пустых скобок.
     */
    fun snapshot(): String = active.entries
        .sortedBy { it.key }
        .joinToString(" ") { (name, period) -> "$name:${period / 1000.0}s" }

    /** Сколько задач сейчас заявлено. Для тестов и экрана диагностики. */
    fun count(): Int = active.size

    /** Только для тестов: реестр — синглтон, и между тестами его надо чистить. */
    internal fun clearForTest() {
        active.clear()
    }
}
